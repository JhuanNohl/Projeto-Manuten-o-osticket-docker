    <h1>TERMO DE GARANTIA E POLÍTICA DE MANUTENÇÃO — ZKTECO DO BRASIL</h1>
  </div>

  <p class="zk-doc-intro">Este termo estabelece as condições de garantia, manutenção e assistência técnica dos equipamentos ZKTeco no Brasil e aplica-se a consumidores finais, revendedores e distribuidores, observadas as disposições específicas indicadas ao final.</p>

  <hr>

  <h2>1. Disposições Gerais</h2>

  <p>A ZKTECO do Brasil oferece <strong>12 (doze) meses de garantia de hardware</strong>, contados a partir da data de emissão da <em>commercial invoice</em>, que é o comprovante da data de compra. Todas as solicitações de cobertura devem ser feitas antes do final do período de garantia.</p>

  <p>Estão <strong>incluídos</strong> na política de garantia os equipamentos controladores de acesso, de frequência, painéis controladores e leitores.</p>

  <p><strong>Não estão cobertos</strong> por esta política os equipamentos acessórios, cartões, tags, cabos, trancas, fontes de alimentação e componentes avulsos retirados de dispositivos.</p>

  <p>A ZKTECO do Brasil garante que os equipamentos adquiridos estão livres de qualquer defeito de fabricação e funcionam corretamente dentro de suas especificações técnicas, consideradas condições normais de utilização.</p>

  <p>A garantia se aplica somente a equipamentos adquiridos em cadeia de distribuição autorizada e reconhecida pela ZKTECO do Brasil em território nacional. Durante o período de garantia, a ZKTECO do Brasil poderá, a seu critério, reparar ou substituir o equipamento defeituoso por outro similar — entende-se por equipamento similar aquele que possua as mesmas funcionalidades do equipamento a ser substituído.</p>

  <p>Equipamentos adquiridos fora do Brasil poderão ser manutenidos, mas <strong>não estão cobertos</strong> pela garantia ZKTeco do Brasil. A manutenção desses equipamentos limita-se exclusivamente à troca de peças e componentes, quando houver compatibilidade e disponibilidade em estoque da ZKTECO do Brasil. Alterações relacionadas à regionalização do equipamento, como troca de firmware e idioma, não são permitidas.</p>

  <p>O prazo máximo de reparo é de <strong>30 dias</strong>, podendo ser reduzido ou ampliado conforme o volume de trabalho ou a disponibilidade de peças para reposição. O prazo de garantia para equipamentos reparados é de <strong>3 meses</strong>, contados a partir da data de devolução do equipamento.</p>

  <hr>

  <h2>2. Cobertura da Garantia</h2>

  <p>A garantia <strong>não se aplica</strong> a equipamentos que não estejam devidamente identificados com seu número de série, nem a componentes retirados do produto. O produto deve, impreterivelmente, ser enviado completo para ser coberto pela garantia.</p>

  <p>Durante a manutenção, a ZKTECO do Brasil não se responsabiliza por qualquer perda de dados armazenados nos equipamentos.</p>

  <p><strong>Componentes e serviços cobertos:</strong></p>
  <ul>
    <li>Mainboards</li>
    <li>Coreboards</li>
    <li>Telas simples e sensíveis ao toque</li>
    <li>Placas de comunicação</li>
    <li>Módulos</li>
    <li>Mão de obra</li>
    <li>Frete de retorno</li>
  </ul>

  <p><strong>Componentes e serviços não cobertos:</strong></p>
  <ul>
    <li>Lentes</li>
    <li>Caixas plásticas e metálicas</li>
    <li>Atualizações de firmware não autorizadas</li>
    <li>Mão de obra gasta em produtos não defeituosos</li>
  </ul>

  <p><strong>Danos não cobertos.</strong> Também não estão cobertos pela garantia os equipamentos danificados por:</p>
  <ul>
    <li>Acidentes de qualquer natureza, mau uso, impacto, queda, vandalismo, surto elétrico ou evento similar;</li>
    <li>Desastres naturais como inundações, incêndios e descargas elétricas;</li>
    <li>Utilização incorreta ou fora dos padrões definidos no manual do equipamento;</li>
    <li>Uso conjunto a outros equipamentos não fabricados pela ZKTECO;</li>
    <li>Modificação não autorizada de hardware, firmware ou software.</li>
  </ul>

  <hr>

  <h2>3. Frete</h2>

  <p>A ZKTECO do Brasil não se responsabiliza por custos de frete, postagem ou transporte de qualquer natureza. Todos os equipamentos enviados para a ZKTECO do Brasil deverão ter os custos de envio pagos pelo remetente. <strong>Equipamentos enviados com frete a cobrar não serão recebidos.</strong></p>

  <p>Após o reparo, a ZKTECO do Brasil notificará o cliente via e-mail e disponibilizará os equipamentos para coleta. Os custos de frete para a devolução também são de responsabilidade do cliente.</p>

  <p>Em casos excepcionais, o frete poderá ser arranjado e/ou custeado pela ZKTECO do Brasil, mediante consentimento prévio da ZKTECO do Brasil, via e-mail.</p>

  <hr>

  <h2>4. Notificação Prévia e Abertura de RMA</h2>

  <p>Antes de enviar qualquer equipamento para a assistência técnica, é necessário notificar previamente a ZKTECO do Brasil da intenção de envio, fornecendo informações sobre os equipamentos e os problemas observados.</p>

  <p>Os equipamentos somente deverão ser enviados <strong>após a confirmação da ZKTECO do Brasil via e-mail</strong>, momento em que será enviado um código de identificação de abertura do RMA. <strong>Equipamentos enviados sem notificação prévia não serão recebidos.</strong></p>

  <p>Caso sejam enviados produtos sem o código RMA e a documentação necessária, será cobrada hora técnica para análise e processamento do produto, no valor equivalente a <strong>15 minutos</strong> do valor da hora técnica.</p>

