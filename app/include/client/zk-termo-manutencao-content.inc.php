  <h2>7. Armazenagem</h2>

  <p>Os equipamentos disponibilizados para coleta deverão ser retirados em até <strong>5 (cinco) dias úteis</strong> após a notificação do cliente. Após esse período, será cobrada taxa adicional de armazenagem de <strong>R$ 1,00 (um real) por dia</strong>, para cada equipamento não retirado.</p>

