  <h2>6. Reparo fora da Garantia</h2>

  <p>Qualquer produto defeituoso que demande reparo e que não esteja dentro do período de garantia poderá ser reparado pela ZKTECO do Brasil. Nesse caso, todos os custos de reparo — peças, componentes, mão de obra e frete — são cobrados. Equipamentos adquiridos fora do Brasil não estão cobertos pela garantia da ZKTECO do Brasil.</p>

  <p>Ao receber os equipamentos, a ZKTECO do Brasil realiza uma análise técnica para identificação do problema e geração de um orçamento de reparo.</p>

  <p>Em caso de <strong>não aprovação</strong> do reparo, ou de equipamentos que chegarem à manutenção sem apresentar falhas, será cobrado o valor de <strong>R$ 90,00 (noventa reais) por equipamento</strong>, a título de remuneração das horas gastas na avaliação e confecção do laudo técnico; os equipamentos serão então disponibilizados para retirada sem manutenção.</p>

  <p>Em caso de <strong>aprovação</strong> do serviço, a manutenção será realizada somente após o pagamento do valor orçado. Após a manutenção, os equipamentos serão disponibilizados para retirada.</p>

