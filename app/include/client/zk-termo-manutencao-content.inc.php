  <h2>8. Disposições Específicas para Revendedores e Distribuidores</h2>

  <h3>8.1. Distribuidores capacitados a prestar assistência técnica</h3>
  <p>Distribuidores capacitados a prestar assistência técnica são responsáveis pela compra e manutenção do seu próprio estoque de peças de reposição. Os valores cobrados por esses distribuidores pelos serviços de manutenção e venda de peças ficam a seu critério, bem como sua política de manutenção.</p>

  <h3>8.2. Distribuidores e clientes não capacitados a prestar assistência técnica</h3>
  <p>Distribuidores e demais clientes não capacitados a prestar serviços de assistência técnica poderão enviar equipamentos para manutenção na ZKTECO do Brasil, observando todos os procedimentos e condições descritos neste termo.</p>

  <h3>8.3. Cobertura de garantia junto à fábrica</h3>
  <p>Nos casos em que os equipamentos manutenidos apresentarem defeito de fabricação e estiverem no período de garantia, o distribuidor poderá solicitar à ZK China a reposição do equipamento ou das peças utilizadas na manutenção. A reposição das peças utilizadas na manutenção de equipamentos em garantia poderá ocorrer sem cobrança das peças pela fábrica; contudo, todas as demais despesas são de responsabilidade do distribuidor (impostos, frete, desembaraço, etc.).</p>

  <p>Antes da solicitação de reposição de peças ou equipamentos em garantia, é necessário que o distribuidor envie os equipamentos com defeito para a ZK Brasil, para avaliação e emissão de laudo técnico. Os equipamentos serão avaliados e devolvidos ao distribuidor, independentemente de apresentarem defeito ou não. Uma vez confirmado o problema e a cobertura da garantia, será autorizada a solicitação de equipamento ou peça para reposição, e o frete de devolução do equipamento para o distribuidor será custeado pela ZK Brasil.</p>

